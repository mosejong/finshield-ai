"""서비스가 쓰는 "오늘".

컨테이너는 UTC 로 돈다. 사용자는 한국에 있다. 두 시각이 같은 날짜를 가리키지
않는 구간이 매일 9시간(00:00~09:00 KST) 있고, 그 구간에서 `date.today()` 는
사용자 기준으로 **어제**를 돌려준다.

그래서 어긋나는 곳이 둘이다.

1. 전입신고일. 오전 7시에 신고를 마친 사용자가 오늘 날짜를 입력하면 서버는
   그것을 미래 날짜로 보고 거부한다. 사용자는 자기가 방금 한 일을 입력하지
   못한다.
2. 공식 출처의 `retrieved_at`. 오늘 확인한 링크를 오늘 날짜로 적어 두고 그날
   아침에 배포하면, 기동 시점 무결성 검사가 "미래 날짜" 로 판단해 앱이 아예
   뜨지 않는다.

둘 다 사람이 겪을 때는 원인이 전혀 보이지 않는 종류의 오류다. 그래서 시각의
기준을 모듈 하나에 두고 날짜가 필요한 곳은 전부 여기를 거친다.

**모든 시각을 여기로 옮기지는 않는다.** 세션 만료, 보존 기간, rate limit 창은
"사용자에게 오늘이 며칠인가" 를 묻지 않고 두 시각의 간격만 본다. 그런 곳은
UTC 가 맞고, 그대로 둔다. 여기를 거쳐야 하는 것은 **달력 날짜**를 다루는
코드다.
"""

from datetime import date, datetime, timedelta, timezone


SEOUL = timezone(timedelta(hours=9), name="KST")


def now_kst() -> datetime:
    return datetime.now(SEOUL)


def today_kst() -> date:
    return now_kst().date()
